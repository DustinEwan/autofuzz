// Standalone reproducer rendering, requested by the engine's `reproducer` method.
//
// The engine minimized a finding and confirmed the minimized input reproduces; it then asks
// the plugin — which owns the target language — to render the call. The engine stores the
// returned bytes verbatim under the extension named here. Nothing here imports or executes
// the target: rendering is string work, so it never needs the invocation deadline.
//
// The script mirrors `materialize.ts` semantics exactly, because a reproducer that quietly
// alters an argument calls the target with something the finding never used: a `function`
// becomes the same `makeStub` behavior (including the `StubCallError` class name a `throw`
// stub faults under), a `stream` becomes the same sync-iterable or async-iterator object,
// and an `object` with a `__proto__` field is built with `defineProperty` like the harness
// builds it. The script is `.mjs` and imports the target file directly: Node 23.6+ strips
// type annotations, and the header says what to do when the module uses non-erasable syntax.

import { pathToFileURL } from "node:url";

import type { ValueTree } from "./protocol.js";

export interface ReproducerResp {
  extension: string;
  script: string;
}

interface Helpers {
  stubError: boolean;
  captured: boolean;
}

export function render(targetId: string, file: string, name: string, values: ValueTree[]): ReproducerResp {
  const helpers: Helpers = { stubError: false, captured: false };
  const args = values.map((value) => literal(value, 0, helpers));
  const out = [
    `// autofuzz reproducer for ${targetId}`,
    "// Generated by the js-ts harness at the engine's request; the arguments are the",
    "// finding's minimized input. Run it with Node 23.6+ from anywhere:",
    "//   node <this file>",
    "// Node strips the target's type annotations. If the module uses non-erasable TypeScript",
    "// (enum, namespace, decorators), run this file through the project's own toolchain.",
    "// A deadline finding reproduces by not returning: stop this script once the",
    "// finding's deadline has elapsed. The wall clock is the fault.",
    `import * as afzTarget from ${JSON.stringify(pathToFileURL(file).href)};`,
    "",
  ];
  if (helpers.stubError) {
    // The same class name and message `materialize.ts` raises, so the fault classifies the
    // same way here as it did in the scan.
    out.push(
      "class StubCallError extends Error {",
      "  constructor(argCount) {",
      "    super(`autofuzz stub invoked with ${argCount} argument(s)`);",
      '    this.name = "StubCallError";',
      "  }",
      "}",
      "",
    );
  }
  if (helpers.captured) {
    out.push("const afzCaptured = [];", "");
  }
  const dot = name.indexOf(".");
  if (dot >= 0) {
    out.push("// The receiver is constructed with no arguments: the harness only fuzzes a");
    out.push("// method whose constructor takes none.");
    out.push(`new afzTarget[${JSON.stringify(name.slice(0, dot))}][${JSON.stringify(name.slice(dot + 1))}](${args.join(", ")});`);
  } else {
    out.push(`afzTarget[${JSON.stringify(name)}](${args.join(", ")});`);
  }
  out.push("");
  return { extension: "mjs", script: out.join("\n") };
}

function literal(node: ValueTree, depth: number, helpers: Helpers): string {
  const pad = "  ".repeat(depth + 1);
  const closePad = "  ".repeat(depth);
  switch (node.node) {
    case "null":
      return "null";
    case "undefined":
      return "undefined";
    case "boolean":
      return node.value ? "true" : "false";
    case "number":
      if (typeof node.value === "number") return JSON.stringify(node.value);
      if (node.value === "naN") return "Number.NaN";
      return node.value === "infinity" ? "Number.POSITIVE_INFINITY" : "Number.NEGATIVE_INFINITY";
    case "bigInt":
      return `${node.value}n`;
    case "string":
      return JSON.stringify(node.value);
    case "literal":
      return JSON.stringify(node.value);
    case "array":
    case "tuple":
      return collection(node.items, "[", "]", depth, pad, closePad, helpers);
    case "set":
      if (node.items.length === 0) return "new Set()";
      return `new Set(${collection(node.items, "[", "]", depth, pad, closePad, helpers)})`;
    case "map": {
      if (node.entries.length === 0) return "new Map()";
      const pairs = node.entries.map(
        ([key, value]) => `${pad}[${literal(key, depth + 1, helpers)}, ${literal(value, depth + 1, helpers)}]`,
      );
      return `new Map([\n${pairs.join(",\n")}\n${closePad}])`;
    }
    case "object": {
      // A literal with a `__proto__` key would reparent the object; `materialize.ts` uses
      // defineProperty for every field, so any object carrying that name is built the same way.
      if (node.fields.some(([key]) => key === "__proto__")) {
        if (node.fields.length === 0) return "Object.defineProperties({}, {})";
        const props = node.fields.map(
          ([key, value]) =>
            `${pad}${JSON.stringify(key)}: { value: ${literal(value, depth + 2, helpers)}, writable: true, enumerable: true, configurable: true }`,
        );
        return `Object.defineProperties({}, {\n${props.join(",\n")}\n${closePad}})`;
      }
      if (node.fields.length === 0) return "{}";
      const fields = node.fields.map(([key, value]) => `${pad}${JSON.stringify(key)}: ${literal(value, depth + 1, helpers)}`);
      return `{\n${fields.join(",\n")}\n${closePad}}`;
    }
    case "buffer":
      // `materialize.ts` defaults to `uint8Array` and no target config overrides it.
      return `new Uint8Array([${node.bytes.join(", ")}])`;
    case "function": {
      const returns = node.returns === undefined || node.returns === null ? "undefined" : literal(node.returns, depth, helpers);
      if (node.behavior === "throw") {
        helpers.stubError = true;
        return "(function (...args) { throw new StubCallError(args.length); })";
      }
      if (node.behavior === "captureArguments") {
        helpers.captured = true;
        return `(function (...args) { afzCaptured.push({ args, this: this }); return ${returns}; })`;
      }
      // `makeStub` returns the built `returns` for every non-throw behavior.
      return `(function () { return ${returns}; })`;
    }
    case "stream": {
      const items = collection(node.items, "[", "]", depth, pad, closePad, helpers);
      if (node.iterable) {
        return `{ [Symbol.iterator]: () => ${items}[Symbol.iterator]() }`;
      }
      return `{ [Symbol.asyncIterator]: async function* () { for (const item of ${items}) yield item; } }`;
    }
    case "opaque":
      return `undefined /* opaque ${node.ty}: a fixture is needed to build it */`;
  }
}

function collection(
  items: ValueTree[],
  open: string,
  close: string,
  depth: number,
  pad: string,
  closePad: string,
  helpers: Helpers,
): string {
  if (items.length === 0) return open + close;
  const entries = items.map((item) => `${pad}${literal(item, depth + 1, helpers)}`);
  return `${open}\n${entries.join(",\n")}\n${closePad}${close}`;
}
