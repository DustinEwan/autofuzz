//! A standalone `.ts` file that reproduces one finding.
//!
//! The reproducer imports the target's own module and calls it with the minimized arguments, so
//! it needs neither the engine nor the plugin: `node --experimental-strip-types` on the file is
//! the whole reproduction. That is the artifact a triager attaches to a bug report, and the one
//! check that the minimized input is real rather than merely small.

use afz_protocol::{FunctionBehavior, ValueNode, ValueTree};

/// Where the call goes.
#[derive(Debug, Clone)]
pub struct ReproTarget<'a> {
    /// The `afz:t:…` id, recorded so the file can be traced back to the finding.
    pub target_id: &'a str,
    /// `Origin.file`: the source file discovery read the symbol from, absolute.
    pub file: &'a str,
    /// The exported symbol, or `Receiver.method` for a method on an exported object.
    pub symbol: &'a str,
}

/// The contents of the reproducer.
pub fn reproducer(target: &ReproTarget<'_>, values: &[ValueTree]) -> String {
    let mut out = String::new();
    out.push_str(&format!("// autofuzz reproducer for {}\n", target.target_id));
    out.push_str("// Generated by the engine; the arguments are the finding's minimized input.\n");
    out.push_str("// Run it with Node 24 from anywhere inside the target project:\n");
    out.push_str("//   node --experimental-strip-types <this file>\n");

    // A dotted symbol is a member access on an exported object; discovery reports methods that
    // way, and the import has to name the object rather than the method.
    let (imported, callee) = match target.symbol.split_once('.') {
        Some((head, rest)) => (head, format!("{head}.{rest}")),
        None => (target.symbol, target.symbol.to_string()),
    };
    out.push_str(&format!("import {{ {imported} }} from {};\n\n", import_specifier(target.file)));
    let args: Vec<String> = values.iter().map(|value| literal(&value.node, 0)).collect();
    out.push_str(&format!("{callee}({});\n", args.join(", ")));
    out
}

/// An ESM specifier Node can resolve from anywhere in the project: a file URL for an absolute
/// path, and the given specifier untouched otherwise.
fn import_specifier(file: &str) -> String {
    let quoted = serde_json::to_string(file).unwrap_or_else(|_| format!("\"{file}\""));
    if file.starts_with("file:") || file.starts_with('.') {
        return quoted;
    }
    #[cfg(windows)]
    {
        if let (Some(drive), Some(rest)) = (file.get(0..2), file.get(2..)) {
            if drive.ends_with(':') {
                return serde_json::to_string(&format!("file:///{drive}{}", rest.replace('\\', "/"))).unwrap_or(quoted);
            }
        }
    }
    if file.starts_with('/') {
        return serde_json::to_string(&format!("file://{file}")).unwrap_or(quoted);
    }
    quoted
}

/// TypeScript source for one node. Every case is covered, because a reproducer that quietly
/// drops an argument would call the target with something the finding never used.
fn literal(node: &ValueNode, depth: usize) -> String {
    let pad = "  ".repeat(depth + 1);
    let close_pad = "  ".repeat(depth);
    match node {
        ValueNode::Null => "null".to_string(),
        ValueNode::Undefined => "undefined".to_string(),
        ValueNode::Boolean { value } => value.to_string(),
        ValueNode::Number { value } => {
            let v = value.as_f64();
            if v.is_nan() {
                "NaN".to_string()
            } else if v.is_infinite() {
                if v > 0.0 { "Infinity".to_string() } else { "(-Infinity)".to_string() }
            } else {
                format!("{v}")
            }
        }
        ValueNode::BigInt { value } => format!("{value}n"),
        ValueNode::String { value } => serde_json::to_string(value).unwrap_or_else(|_| "\"\"".to_string()),
        ValueNode::Literal { value } => serde_json::to_string(value).unwrap_or_else(|_| "null".to_string()),
        ValueNode::Buffer { bytes } => {
            let items: Vec<String> = bytes.iter().map(|b| b.to_string()).collect();
            format!("new Uint8Array([{}])", items.join(", "))
        }
        ValueNode::Array { items } | ValueNode::Tuple { items } => collection(items, "[", "]", depth, &pad, &close_pad),
        ValueNode::Stream { items, iterable } => {
            // There is no standalone way to hand back the stream object the plugin built. An
            // array iterates the same way, which is what a target that consumes it sees.
            let _ = iterable;
            collection(items, "[", "]", depth, &pad, &close_pad)
        }
        ValueNode::Set { items } => format!("new Set({})", collection(items, "[", "]", depth, &pad, &close_pad)),
        ValueNode::Map { entries } => {
            if entries.is_empty() {
                return "new Map()".to_string();
            }
            let pairs: Vec<String> = entries
                .iter()
                .map(|(k, v)| format!("{pad}[{}, {}]", literal(&k.node, depth + 1), literal(&v.node, depth + 1)))
                .collect();
            format!("new Map([\n{}{}\n{close_pad}])", pairs.join(",\n"), "")
        }
        ValueNode::Object { fields } => {
            if fields.is_empty() {
                return "{}".to_string();
            }
            let entries: Vec<String> = fields
                .iter()
                .map(|(key, value)| format!("{pad}{}: {}", json_key(key), literal(&value.node, depth + 1)))
                .collect();
            format!("{{\n{}{}\n{close_pad}}}", entries.join(",\n"), "")
        }
        ValueNode::Function { behavior, returns } => match behavior {
            FunctionBehavior::ReturnFirst => "((...args: unknown[]) => args[0])".to_string(),
            FunctionBehavior::Throw => "((..._args: unknown[]) => { throw new Error(\"autofuzz stub\"); })".to_string(),
            FunctionBehavior::CaptureArguments => {
                let _ = returns;
                "((...args: unknown[]) => { (globalThis as { __afzCaptured?: unknown[] }).__afzCaptured = args; return undefined; })".to_string()
            }
        },
        ValueNode::Opaque { ty } => format!("undefined /* opaque {ty}: a fixture is needed to build it */"),
    }
}

fn collection(items: &[ValueTree], open: &str, close: &str, depth: usize, pad: &str, close_pad: &str) -> String {
    if items.is_empty() {
        return format!("{open}{close}");
    }
    let entries: Vec<String> = items.iter().map(|item| format!("{pad}{}", literal(&item.node, depth + 1))).collect();
    format!("{open}\n{}{close_pad}{close}", entries.join(",\n"))
}

/// A field name as a key: bare where TypeScript allows it, quoted where it does not.
fn json_key(key: &str) -> String {
    let identifier = !key.is_empty()
        && !is_reserved(key)
        && key.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if identifier {
        key.to_string()
    } else {
        serde_json::to_string(key).unwrap_or_else(|_| format!("\"{key}\""))
    }
}

fn is_reserved(key: &str) -> bool {
    matches!(
        key,
        "await" | "break" | "case" | "catch" | "class" | "const" | "continue" | "debugger" | "default" | "delete" | "do" | "else"
            | "enum" | "export" | "extends" | "false" | "finally" | "for" | "function" | "if" | "import" | "in" | "instanceof"
            | "new" | "null" | "return" | "super" | "switch" | "this" | "throw" | "true" | "try" | "typeof" | "var" | "void"
            | "while" | "with" | "yield"
    )
}
